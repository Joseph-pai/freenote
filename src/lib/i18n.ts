export function useTranslation() {
  const { user } = useAuthStore();
  const lang = user?.language === 'en' ? 'en' : 'zh-TW';
  
  const t = (key: string): string => {
    return dictionaries[lang]?.[key] || dictionaries['zh-TW']?.[key] || key;
  };

  return { t, lang };
}
